// Writes docs/plans/mechanism-tree-labels.md, the mechanism tree's clinical labels for the owner's review, from
// apps/demo/src/app/mechanisms/labels.ts (brief 104). apps/demo's labels.test.ts fails when the page is stale.
//   node --experimental-strip-types scripts/mechanism-labels.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { labelsTable, NODE_LABELS } from '../apps/demo/src/app/mechanisms/labels.ts';

export const LABELS_DOC = resolve(import.meta.dirname, '../docs/plans/mechanism-tree-labels.md');
const BEGIN = '<!-- labels:begin (generated by scripts/mechanism-labels.ts from apps/demo/src/app/mechanisms/labels.ts) -->';
const END = '<!-- labels:end -->';

export function labelsDoc(): string {
  const g = NODE_LABELS.filter((l) => l.glossary).length;
  return `# The mechanism tree's clinical labels (for the owner's review)

The mechanism tree page (\`#/explore/mechanisms\`, plan [mechanism-tree.md](mechanism-tree.md) pieces T1 and T1b) names
every node by the clinical label below, never by its engine key (the key stays in the node's tooltip). The table holds
every node the coupling registry names (\`packages/engine-core/src/couplings/\`): **${NODE_LABELS.length} nodes**, of which
**${g}** carry the clinical glossary's label unchanged (\`apps/demo/src/app/glossary.ts\`, From = glossary) and
**${NODE_LABELS.length - g}** were written for the tree (From = tree).

Every row is a draft until the clinical owner reads it: \`reviewed\` is \`false\` on every row, and the page shows the line
"labels under the owner's review" while any label it draws is unreviewed. To record a review, set \`reviewed\` (or
correct the words) in \`apps/demo/src/app/mechanisms/labels.ts\` and regenerate this page with
\`node --experimental-strip-types scripts/mechanism-labels.ts\`; \`apps/demo/src/app/mechanisms/labels.test.ts\` fails
when the two differ, when a registry node has no row, or when a glossary row no longer equals the glossary. A
glossary label is corrected in the glossary, not here. Persian labels enter the i18n table later, through the usual
route.

A unit "×" is a factor (1 = no change); "fraction" and "0–1" are dimensionless shares; "a.u." the model's own units.

${BEGIN}
${labelsTable()}
${END}
`;
}

const invokedDirectly = process.argv[1] !== undefined && resolve(process.argv[1]) === resolve(import.meta.filename);
if (invokedDirectly) {
  const next = labelsDoc();
  let prev = '';
  try { prev = readFileSync(LABELS_DOC, 'utf8'); } catch { /* first write */ }
  if (prev !== next) writeFileSync(LABELS_DOC, next);
  console.log(`${LABELS_DOC}: ${NODE_LABELS.length} rows${prev === next ? ' (unchanged)' : ' written'}`);
}
