// Known misses: docs/validation/known-misses.md, GENERATED. Every expected-failure test (`it.fails`, Playwright's
// `test.fail`) listed by scripts/deviations.ts — the one lister, also behind docs/guides/known-deviations.md — is a
// published band the model does not meet yet (the band is kept, the miss recorded). This index groups them by the
// module that owns the test (scripts/model-modules.ts) and splits each title into target / measured / source by the
// rules below; a field the rules cannot find is written "—", never guessed.
//   node --experimental-strip-types scripts/known-misses.ts           → writes docs/validation/known-misses.md
//   node --experimental-strip-types scripts/known-misses.ts --check   → exit 1 if the committed file is stale
// packages/validation/test/model-docs.test.ts runs the same check.
// Each miss also shows the target audit's verdict on its band and the audit's proposed band, read from
// docs/validation/target-audit.tsv (generated by scripts/import-audit.py from the published audit in
// docs/validation/target-audit/, keyed by the current test file and title). When the audit changes, or a test it graded
// is re-worded or moved: re-run `python3 scripts/import-audit.py --repo` (a moved or re-worded test first gets a row in
// docs/validation/target-audit/overrides.tsv), then this script; --check fails while an audit row marked `matched`
// names a test that is no longer an expected failure.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { type Deviation, listDeviations } from './deviations.ts';
import { MODULES, type ModelModule, ownerOfTest } from './model-modules.ts';

export interface AuditRow {
  row: string;
  kind: 'fails' | 'passing' | 'list' | 'queue';
  status: 'matched' | 'now-passing' | 'unmatched' | 'unlisted' | 'not-a-test';
  file: string;
  title: string;
  verdict: string;
  proposed_band: string;
  proposed_sources: string;
  grade: string;
  likely_not_a_miss: string;
  audit_band: string;
  measured: string;
}

export interface Miss extends Deviation {
  module: ModelModule;
  target: string;
  measured: string;
  source: string;
  band: boolean;
  audit: AuditRow[];
}

export const AUDIT_FILE = 'docs/validation/target-audit.tsv';
/** The published audit (Question 7); each row has an anchor `row-N`. */
export const AUDIT_MD = 'docs/validation/target-audit/30-target-audit.md';
export const VERDICTS = ['RIGHT', 'TOO NARROW', 'TOO WIDE', 'MIS-SPECIFIED', 'UNSUPPORTED'] as const;

/** The audit rows (docs/validation/target-audit.tsv); none when the file does not exist. */
export function readAudit(root: string): AuditRow[] {
  let text = '';
  try {
    text = readFileSync(join(root, AUDIT_FILE), 'utf8');
  } catch {
    return [];
  }
  const lines = text.split('\n').filter((l) => l && !l.startsWith('#'));
  const cols = (lines.shift() ?? '').split('\t');
  return lines.map((l) => Object.fromEntries(l.split('\t').map((v, i) => [cols[i], v])) as unknown as AuditRow);
}

const NONE = '—';
/** "measured" (not "measurement") at paren depth 0, or starting a clause inside one: "(measured 14.0)", "(Q15; measured …)". */
const MEASURED_RE = /\bmeasured\b:?\s*/gi;
/** The measured value ends at a history connector, a new clause, or the end of its parenthesis. */
const MEASURED_END = /\s\(|;\s|:\s|\s—\s|\)|\s(?:after|before|on the|with the|at the gate|in this rig|in the engine)\b/;
/** A citation: author(s) + year, a section of a document in the repo, a research row id, a textbook or guideline. */
const SOURCE_TOKEN =
  /\b[A-Z][A-Za-z'’-]+(?:\s(?:&|and)\s[A-Z][A-Za-z'’-]+|\set al\.?)?,?\s(?:19|20)\d\d\b|\b(?:tables?|annex|catalogue|brief|research)\s?\/?\s?(?:§|\d)[\w.§ -]*|\bmain §[\w.]*|\b(?:DI|SP|RH|CM|ET|DV|DP)-\d+[a-z]?\b|\b(?:M10|Miller|Nunn|ATLS|PALS|WSACS|ASRA|ESC\/ERS|HeartMate \d|ALS)\b[^;):—]*/;
/** A target is recognised when the text states a band: a comparator, a range, a direction with a number. */
const BAND_RE =
  /[≥≤<>±×]|\d\s?[–-]\s?[−+]?\d|→\s?[−+]?\d|\d\s?%|\b(?:within|by|below|above|reaches|at least|at most|no more than|no faster than)\b|\b(?:more|less|fewer|higher|lower|faster|slower) than\b/;

function depthAt(text: string, i: number): number {
  let d = 0;
  for (let k = 0; k < i; k++) d += text[k] === '(' ? 1 : text[k] === ')' ? -1 : 0;
  return d;
}

/** Split one expected-failure title into target, measured value and source; NONE where the rules find nothing. */
export function parseTitle(title: string): { target: string; measured: string; source: string; band: boolean } {
  const m = [...title.matchAll(MEASURED_RE)].find((x) => depthAt(title, x.index) === 0 || /(?:\(|;\s)$/.test(title.slice(0, x.index)));
  let measured = NONE;
  let head = title;
  if (m) {
    const rest = title.slice(m.index + m[0].length);
    const end = MEASURED_END.exec(rest);
    measured = (end ? rest.slice(0, end.index) : rest).replace(/[\s,.:]+$/, '').trim() || NONE;
    head = title.slice(0, m.index).replace(/(?:\(|;\s)$/, '');
  }
  // sources: the citation in each parenthesised or ;-separated segment of the head, in order, de-duplicated
  const segments = [...head.matchAll(/\(([^()]*)\)/g)].flatMap((p) => (p[1] as string).split(/;\s*/));
  const bare = head.replace(/\([^()]*\)/g, ' ').split(/;\s*|,\s(?=[A-Z])/);
  const sources = [...new Set([...segments, ...bare].map((s) => SOURCE_TOKEN.exec(s)?.[0]?.trim()).filter((s): s is string => !!s))];
  // the target: the head without parentheses that hold only citations (and question/ruling ids)
  const citationOnly = (inner: string) => inner.split(/;\s*/).every((s) => SOURCE_TOKEN.test(s) || /^(?:Q[-\w]*|R[-\w]+)$/.test(s.trim()));
  const target = head
    .replace(/\s*\(([^()]*)\)/g, (all, inner: string) => (citationOnly(inner) ? '' : all))
    .replace(/[\s—–,;:(]+$/, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
  return { target: target || NONE, measured, source: sources.length ? sources.join('; ') : NONE, band: BAND_RE.test(target) };
}

export function listMisses(root: string): Miss[] {
  const audit = readAudit(root).filter((a) => a.status === 'matched');
  const misses = listDeviations(root).map((d) => {
    const owner = ownerOfTest(d.file).module;
    if (!owner) throw new Error(`known-misses: no module owns ${d.file} (scripts/model-modules.ts)`);
    return { ...d, module: owner, ...parseTitle(d.title), audit: audit.filter((a) => a.file === d.file && a.title === d.title) };
  });
  const dangling = audit.filter((a) => !misses.some((x) => x.audit.includes(a)));
  if (dangling.length)
    throw new Error(`known-misses: ${AUDIT_FILE} rows ${dangling.map((a) => a.row).join(', ')} name a test that is not an expected failure any more: add each row's current file and title to docs/validation/target-audit/overrides.tsv (or fix the test), then re-run python3 scripts/import-audit.py --repo`);
  return misses;
}

const verdictCell = (rows: AuditRow[], linkPrefix: string) =>
  rows.length ? rows.map((a) => `${a.verdict} ([audit row ${a.row}](${linkPrefix}${AUDIT_MD}#row-${a.row}))`).join('; ') : 'not audited';
const bandCell = (rows: AuditRow[]) => (rows.length ? rows.map((a) => a.proposed_band || NONE).join('; ') : NONE);

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** The rows of one module's table (also used by the module's page in docs/model/). */
export function missRows(misses: Miss[], linkPrefix: string): string[] {
  return [
    '| Target (band) | Measured | Source | Audit verdict | Audit\'s proposed band | Test |',
    '|---|---|---|---|---|---|',
    ...misses.map(
      (x) =>
        `| ${cell(x.target)} | ${cell(x.measured)} | ${cell(x.source)} | ${cell(verdictCell(x.audit, linkPrefix))} | ${cell(bandCell(x.audit))} | [\`${x.file.split('/').pop()}\`](${linkPrefix}${x.file}) |`,
    ),
  ];
}

export function renderKnownMisses(root: string): string {
  const misses = listMisses(root);
  const parsed = (k: 'measured' | 'source') => misses.filter((x) => x[k] !== NONE).length;
  const out = [
    '# Known misses',
    '',
    '<!-- GENERATED by scripts/known-misses.ts from the expected-failure tests; do not edit. Regenerate:',
    '     node --experimental-strip-types scripts/known-misses.ts -->',
    '',
    'Every test below states a band taken from a published source that the model does not meet yet. The band is kept',
    'and the test is marked as an expected failure with the measured value in its title; it is listed here, by the',
    'module that owns it, until the mechanism is fixed. The release-candidate view of the same list, with where each',
    'item is tracked, is [known deviations](../guides/known-deviations.md); each module is described in [docs/model](../model/README.md).',
    '',
    `**${misses.length} known misses.** Split from the test titles: a band recognised in the target of ${misses.filter((x) => x.band).length}, a measured value in ${parsed('measured')}, a source in ${parsed('source')}; "—" = not stated in a form the generator reads.`,
    '',
    `**The bands themselves were audited** against the literature (target audit, 2026-10-11; the rows are in [target-audit.tsv](target-audit.tsv)): ` +
      `${misses.filter((x) => x.audit.length).length} of these misses carry an audit verdict — ` +
      VERDICTS.map((v) => `${v} ${misses.filter((x) => x.audit.some((a) => a.verdict === v)).length}`).join(', ') +
      ` (a miss can carry several rows). RIGHT: the band matches its source; TOO NARROW / TOO WIDE: the source supports a wider / narrower band; ` +
      `MIS-SPECIFIED: the band measures something other than its source did; UNSUPPORTED: no source found for it. A proposed band is evidence ` +
      `for an owner ruling, not a change: until a ruling, the test keeps its band. The audit itself, row by row with its evidence, is ` +
      `[published here](target-audit/30-target-audit.md) with its CSV twin and synthesis; the numbered evidence notes it cites as ` +
      `"research/NN" live in the project's research folder outside the repository.`,
    '',
    '| Module | Misses |',
    '|---|---|',
    ...MODULES.filter((m) => misses.some((x) => x.module === m)).map((m) => `| [${m.title}](#${m.id}) | ${misses.filter((x) => x.module === m).length} |`),
  ];
  for (const m of MODULES) {
    const mine = misses.filter((x) => x.module === m);
    if (!mine.length) continue;
    out.push('', `<a id="${m.id}"></a>`, `## ${m.title}`, '', `Module page: [docs/model/${m.id}.md](../model/${m.id}.md)`, '', ...missRows(mine, '../../'));
  }
  const rest = readAudit(root).filter((a) => a.status !== 'matched');
  if (rest.length) {
    const kind: Record<string, string> = {
      queue: 'calibration queue',
      list: 'a known-miss list in a test',
      passing: 'a passing test (a hidden miss)',
      fails: 'an expected failure the lister cannot read',
    };
    out.push(
      '',
      '<a id="audited-elsewhere"></a>',
      '## Audited targets that are not in the list above',
      '',
      'Calibration-queue rows, entries of a known-miss list inside a test, passing tests the audit flags as hidden misses, and',
      'expected failures that are no longer one (the test now passes) or that the lister cannot read.',
      '',
      '| Audit row | Where | What | Verdict | Audit\'s proposed band |',
      '|---|---|---|---|---|',
      ...rest.map((a) => `| [${a.row}](target-audit/30-target-audit.md#row-${a.row}) | ${a.status === 'now-passing' ? 'no longer an expected failure' : kind[a.kind]}: \`${cell(a.file)}\` | ${cell(a.title)} | ${cell(a.verdict)} | ${cell(a.proposed_band || NONE)} |`),
    );
  }
  return out.join('\n') + '\n';
}

const invokedDirectly = process.argv[1] !== undefined && resolve(process.argv[1]) === resolve(import.meta.filename);
if (invokedDirectly) {
  const root = resolve(import.meta.dirname, '..');
  const path = join(root, 'docs/validation/known-misses.md');
  const text = renderKnownMisses(root);
  if (process.argv.includes('--check')) {
    let old = '';
    try {
      old = readFileSync(path, 'utf8');
    } catch {}
    if (old !== text) {
      console.error('known-misses: docs/validation/known-misses.md is stale; run node --experimental-strip-types scripts/known-misses.ts');
      process.exit(1);
    }
  } else writeFileSync(path, text);
  console.error(`known-misses: ${listMisses(root).length} misses`);
}
